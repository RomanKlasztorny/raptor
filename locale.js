var CURR_LANG = localStorage.getItem('raptor_lang') || 'ru';

function t(key) {
  return (LOCALE[CURR_LANG] && LOCALE[CURR_LANG][key]) || LOCALE.ru[key] || key;
}

// Resolves a multilingual task string: {ru,en,ua,pl,es,de} | plain string | fn(lang)=>string
function tTask(obj) {
  if (obj === null || obj === undefined) return '';
  if (typeof obj === 'function') return obj(CURR_LANG);
  if (typeof obj === 'string') return obj;
  return obj[CURR_LANG] || obj.en || obj.ru || String(obj);
}

function setLang(lang) {
  CURR_LANG = lang;
  localStorage.setItem('raptor_lang', lang);
  var flags = {ru:'🇷🇺',en:'🇬🇧',ua:'🇺🇦',pl:'🇵🇱',es:'🇪🇸',de:'🇩🇪'};
  var btn = document.querySelector('#lang-btn');
  if (btn) btn.textContent = (flags[lang]||'🌐') + ' ' + lang.toUpperCase();
  applyLocale();
  if (typeof buildPalette === 'function') buildPalette();
  if (typeof analyze === 'function') analyze();
  if (typeof renderTrainer === 'function' && typeof TR !== 'undefined' && TR.open) renderTrainer();
  if (typeof renderLogs === 'function') renderLogs();
  if (typeof renderSaves === 'function' && typeof sideTab !== 'undefined' && sideTab === 'saves') renderSaves();
  if (typeof buildTemplatesMenu === 'function') buildTemplatesMenu();
  if (typeof renderRoutesPanel === 'function') renderRoutesPanel();
}

function applyLocale() {
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    if (key === 'hint_canvas' || key === 'analyze_empty') { el.innerHTML = t(key); }
    else { el.textContent = t(key); }
  });
  document.documentElement.lang = CURR_LANG;
}
